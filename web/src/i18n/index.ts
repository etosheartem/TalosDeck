const STORAGE_KEY = 'talosdeck_lang'
const initialLocale: Locale = (localStorage.getItem(STORAGE_KEY) as Locale) || 'ru'

export const currentLocale = ref<Locale>(initialLocale)

export const setLocale = (lang: Locale) => {
  currentLocale.value = lang
  try {
    localStorage.setItem(STORAGE_KEY, lang)
  } catch (e) {
    console.error('Failed to persist locale', e)
  }
}

